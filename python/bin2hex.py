#!/usr/bin/env python3

import sys
from pathlib import Path


DV_ROOT = Path.home() / "riscv_spike_clean" / "riscv-dv"
DEFAULT_HEX = Path.home() / "riscv_spike_clean" / "rtl" / "tb" / "hexfile.txt"


def bin_to_hex(bin_file, hex_file):
    bin_file = Path(bin_file)
    hex_file = Path(hex_file)

    with bin_file.open("rb") as f:
        data = f.read()

    # Pad to a multiple of 4 bytes
    if len(data) % 4 != 0:
        data += b"\x00" * (4 - len(data) % 4)

    hex_file.parent.mkdir(parents=True, exist_ok=True)

    with hex_file.open("w") as f:
        for i in range(0, len(data), 4):
            word = int.from_bytes(data[i:i + 4], byteorder="little")
            f.write(f"{word:08x}\n")


def find_latest_bin():
    """Find the newest .bin generated by RISCV-DV."""
    candidates = list(DV_ROOT.glob("out_*/asm_test/*.bin"))

    if not candidates:
        return None

    return max(candidates, key=lambda p: p.stat().st_mtime)


def main():
    # Usage modes:
    #
    #   ./bin_to_hex.py
    #       Automatically find newest RISCV-DV .bin
    #       and write to the default RTL hex file.
    #
    #   ./bin_to_hex.py input.bin
    #       Use the specified .bin and default RTL hex file.
    #
    #   ./bin_to_hex.py input.bin output.hex
    #       Explicit input and output paths.

    if len(sys.argv) == 1:
        bin_file = find_latest_bin()
        hex_file = DEFAULT_HEX

        if bin_file is None:
            print("ERROR: No generated .bin file found.")
            print(f"Expected files under: {DV_ROOT}/out_*/asm_test/")
            sys.exit(1)

    elif len(sys.argv) == 2:
        bin_file = Path(sys.argv[1])
        hex_file = DEFAULT_HEX

    elif len(sys.argv) == 3:
        bin_file = Path(sys.argv[1])
        hex_file = Path(sys.argv[2])

    else:
        print("Usage:")
        print("  bin_to_hex.py")
        print("  bin_to_hex.py input.bin")
        print("  bin_to_hex.py input.bin output.hex")
        sys.exit(1)

    if not bin_file.is_file():
        print(f"ERROR: BIN file not found: {bin_file}")
        sys.exit(1)

    bin_to_hex(bin_file, hex_file)

    print(f"Converted: {bin_file}")
    print(f"HEX file: {hex_file}")


if __name__ == "__main__":
    main()
